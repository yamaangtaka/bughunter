			),
			'propose' => array(
				'titulo'    => __( 'Prepare a reviewable proposal', 'ai-bug-hunter' ),
				'alcance'   => __( 'A line-by-line difference and a plain-language repair guide.', 'ai-bug-hunter' ),
				'porque'    => __( 'The administrator can review the evidence and perform the work through their normal maintenance process.', 'ai-bug-hunter' ),
				'consiente' => __( 'Yes, before contacting the selected AI provider.', 'ai-bug-hunter' ),
				'revertir'  => __( 'Not applicable: the proposal is not applied.', 'ai-bug-hunter' ),
				'enforcer'  => 'ABH_Edition::can_apply_external_repairs',
			),
			'export' => array(
				'titulo'    => __( 'Export the diagnosis or proposal', 'ai-bug-hunter' ),
