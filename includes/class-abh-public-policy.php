<?php
/**
 * Read-only policy used by the WordPress.org edition.
 *
 * This file intentionally contains no implementation capable of changing a
 * site file. It preserves the path, proposal, and compatibility APIs used by
 * the diagnostic pipeline while making every application request fail closed.
 *
 * @package AI_Bug_Hunter
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Public-edition product limits.
 */
final class ABH_Limits {

	/**
	 * Critical WordPress bootstrap files excluded from proposals.
	 *
	 * @return array
	 */
	public static function never() {
		return array( 'wp-config.php', 'wp-settings.php', 'wp-load.php', 'wp-blog-header.php' );
	}

	/**
	 * The public edition does not maintain a special executable-file list.
	 *
	 * @return array
	 */
	public static function dropins() {
		return array();
	}

	/**
	 * Relative content directory.
	 *
	 * @return string
	 */
	public static function content_rel() {
		$root = wp_normalize_path( ABSPATH );
		$dir  = wp_normalize_path( WP_CONTENT_DIR );
		if ( 0 === strpos( $dir, trailingslashit( $root ) ) ) {
			return trim( substr( $dir, strlen( trailingslashit( $root ) ) ), '/' );
		}
		return 'wp-content';
	}

	/**
	 * Compatibility method retained for read-only callers.
	 *
	 * @param string $path Relative path.
	 * @return bool
	 */
	public static function is_dropin( $path ) {
		unset( $path );
		return false;
	}

	/**
	 * Whether a path is excluded from proposals.
	 *
	 * @param string $path Relative or absolute path.
	 * @return bool
	 */
	public static function is_never( $path ) {
		$base = strtolower( basename( str_replace( '\\', '/', (string) $path ) ) );
		return in_array( $base, self::never(), true );
	}

	/**
	 * The analysis-only edition has no removable special files.
	 *
	 * @return array
	 */
	public static function removable() {
		return array();
	}

	/**
	 * Compatibility method for legacy callers.
	 *
	 * @param string $path Relative path.
	 * @return bool
	 */
	public static function is_removable( $path ) {
		unset( $path );
		return false;
	}

